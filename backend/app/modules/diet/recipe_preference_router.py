from fastapi import APIRouter,Depends,Response,Query
from app.modules.diet.library_router import LibraryRoute,database_path
from app.modules.diet.recipe_preference_schemas import InventoryInput,TermInput,CompositionInput,PreferenceInput
from app.modules.diet import recipe_preference_service as service
router=APIRouter(prefix='/diet',tags=['食谱库存与禁忌'],route_class=LibraryRoute)
@router.get('/inventory-items')
def inventory(path=Depends(database_path)):return service.inventory(path)
@router.post('/inventory-items',status_code=201)
def add_inventory(data:InventoryInput,path=Depends(database_path)):return service.save_inventory(path,data)
@router.get('/inventory-items/{id}')
def get_inventory(id:int,path=Depends(database_path)):return service.inventory(path,id)
@router.put('/inventory-items/{id}')
def update_inventory(id:int,data:InventoryInput,path=Depends(database_path)):return service.save_inventory(path,data,id)
@router.delete('/inventory-items/{id}',status_code=204)
def delete_inventory(id:int,path=Depends(database_path)):service.delete_inventory(path,id);return Response(status_code=204)
@router.get('/ingredient-terms/resolve')
def resolve(name:str=Query(min_length=1,max_length=100),path=Depends(database_path)):return service.resolve(path,name)
@router.get('/ingredient-terms')
def terms(q:str=Query(default='',max_length=100),path=Depends(database_path)):return service.terms(path,q)
@router.post('/ingredient-terms',status_code=201)
def create_term(data:TermInput,path=Depends(database_path)):return service.save_term(path,data)
@router.get('/ingredient-terms/{id}')
def term(id:int,path=Depends(database_path)):return service.terms(path,id=id)
@router.put('/ingredient-terms/{id}')
def update_term(id:int,data:TermInput,path=Depends(database_path)):return service.save_term(path,data,id)
@router.delete('/ingredient-terms/{id}',status_code=204)
def delete_term(id:int,path=Depends(database_path)):service.delete_term(path,id);return Response(status_code=204)
@router.get('/foods/{id}/composition')
def composition(id:int,path=Depends(database_path)):return service.composition(path,id)
@router.put('/foods/{id}/composition')
def update_composition(id:int,data:CompositionInput,path=Depends(database_path)):return service.save_composition(path,id,data)
@router.get('/food-preferences')
def preferences(path=Depends(database_path)):return service.preferences(path)
@router.post('/food-preferences',status_code=201)
def create_preference(data:PreferenceInput,path=Depends(database_path)):return service.save_preference(path,data)
@router.get('/food-preferences/{id}')
def preference(id:int,path=Depends(database_path)):return service.preferences(path,id)
@router.put('/food-preferences/{id}')
def update_preference(id:int,data:PreferenceInput,path=Depends(database_path)):return service.save_preference(path,data,id)
@router.delete('/food-preferences/{id}',status_code=204)
def delete_preference(id:int,path=Depends(database_path)):service.delete_preference(path,id);return Response(status_code=204)
